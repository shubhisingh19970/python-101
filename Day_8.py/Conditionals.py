#if,else,elif
#if
x = 10
if x > 5 :
    print("x is greater than 5")

# elif
x = 10 
if x > 15 :
    print ("x is greater than 15")
elif x > 5 :
    print("x is greater than 5 but less than 15")

#else
x = 3
if x > 5 :
    print("x is greater than 5")
elif x == 5 :
    print ("x is equal to 5")
else :
    print("x is less than 5")